import { randomBytes, scrypt as scryptCallback, timingSafeEqual } from 'node:crypto';
import { promisify } from 'node:util';

const scrypt = promisify(scryptCallback);
const KEY_LENGTH = 64;
const SALT_LENGTH = 16;
const SCRYPT_OPTIONS = Object.freeze({
  N: 16_384,
  r: 8,
  p: 1,
  maxmem: 64 * 1024 * 1024,
});

/**
 * Hash a password using Node's built-in scrypt implementation.
 * The encoded value stores the algorithm parameters, salt and derived key.
 */
export async function hashPassword(password) {
  if (typeof password !== 'string' || password.length < 12 || password.length > 128) {
    throw new TypeError('Password must be between 12 and 128 characters.');
  }

  const salt = randomBytes(SALT_LENGTH);
  const derivedKey = await scrypt(password, salt, KEY_LENGTH, SCRYPT_OPTIONS);

  return [
    'scrypt',
    SCRYPT_OPTIONS.N,
    SCRYPT_OPTIONS.r,
    SCRYPT_OPTIONS.p,
    salt.toString('base64url'),
    Buffer.from(derivedKey).toString('base64url'),
  ].join('$');
}

/** Verify a password against the encoded scrypt hash. */
export async function verifyPassword(password, encodedHash) {
  if (typeof password !== 'string' || typeof encodedHash !== 'string') return false;

  const parts = encodedHash.split('$');
  if (parts.length !== 6 || parts[0] !== 'scrypt') return false;

  const [, nRaw, rRaw, pRaw, saltRaw, keyRaw] = parts;
  const N = Number(nRaw);
  const r = Number(rRaw);
  const p = Number(pRaw);

  // Accept only the parameters generated by this application.
  if (N !== SCRYPT_OPTIONS.N || r !== SCRYPT_OPTIONS.r || p !== SCRYPT_OPTIONS.p) {
    return false;
  }

  try {
    const salt = Buffer.from(saltRaw, 'base64url');
    const expectedKey = Buffer.from(keyRaw, 'base64url');
    if (salt.length !== SALT_LENGTH || expectedKey.length !== KEY_LENGTH) return false;

    const actualKey = Buffer.from(await scrypt(password, salt, KEY_LENGTH, SCRYPT_OPTIONS));
    return timingSafeEqual(actualKey, expectedKey);
  } catch {
    return false;
  }
}
